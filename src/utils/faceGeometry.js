/**
 * faceGeometry.js
 *
 * Face-shape measurement + classification, isolated from React (audit
 * Phase 17: "isolate the classification rules into a dedicated
 * function/module. Do not scatter thresholds throughout React components.")
 *
 * Replaces src/utils/faceShapeDetector.js (face-api.js, 68 landmarks). Two
 * concrete bugs that module had (see the AI accuracy audit, Critical
 * Finding #4/#5) are fixed here by construction:
 *
 *   1. face-api.js's 68-point model has NO forehead landmarks, so it had to
 *      approximate face height using the raw TinyFaceDetector bounding-box
 *      TOP edge (an unstable signal that shifts with hair coverage and
 *      framing) minus the chin landmark. MediaPipe's 468-point topology
 *      includes a real forehead-top point (index 10) in the SAME coordinate
 *      system as every other landmark, so no box/landmark mixing is needed.
 *
 *   2. Every ratio in the old module was a raw pixel-space delta on an
 *      UNROTATED image -- not rotation-invariant, so head roll directly
 *      distorted every measurement. `alignLandmarks()` below rotates all
 *      landmark points around the eye-line midpoint so the eye line is
 *      horizontal BEFORE any distance is measured (per the implementation
 *      brief, Phase 5: "the actual landmark coordinates used for
 *      measurements must correspond to the aligned coordinate system," not
 *      just a display-side image rotation).
 *
 * Landmark indices are the standard MediaPipe Face Mesh topology
 * (FACEMESH_FACE_OVAL loop + eye-outer-corner anchors), the same 468/478-
 * point scheme already used by src/utils/faceLandmarkerMP.js for the
 * makeup studio -- see that file's docstring for the model/coordinate
 * conventions (normalized [0,1] x/y, denormalize by image width/height).
 *
 * Classification: detectFaceShapeFromLandmarks() uses a logistic-regression
 * model trained on labeled photos (src/data/faceShapeModel.js, generated by
 * personal_color_ai/face_shape/train_landmark_model.py) over the six shapes
 * on the home page. The hand-written threshold tree in classifyFaceShape()
 * is kept only for scripts/calibrate_face_shape.mjs: measured on the same
 * labeled set it scored below the majority-class baseline, it can never
 * output Diamond (forehead/jaw sits near 1.18 for every class) and it has
 * no Triangle branch.
 */

import faceShapeModel from "../data/faceShapeModel.js";

// Standard MediaPipe Face Mesh landmark indices used for measurement.
const IDX = {
  foreheadTop: 10,   // FACEMESH_FACE_OVAL: top-center of the forehead
  chinBottom: 152,   // FACEMESH_FACE_OVAL: bottom-center of the chin
  faceLeft: 234,     // FACEMESH_FACE_OVAL: cheekbone/temple, left side
  faceRight: 454,    // FACEMESH_FACE_OVAL: cheekbone/temple, right side
  jawLeft: 172,      // FACEMESH_FACE_OVAL: jaw corner, left side
  jawRight: 397,     // FACEMESH_FACE_OVAL: jaw corner, right side
  browLeft: 21,      // FACEMESH_FACE_OVAL: upper temple/forehead, left side
  browRight: 251,    // FACEMESH_FACE_OVAL: upper temple/forehead, right side
  eyeOuterLeft: 33,   // outer corner, left eye (used only for roll alignment)
  eyeOuterRight: 263, // outer corner, right eye (used only for roll alignment)
};

const MIN_LANDMARKS = Math.max(...Object.values(IDX)) + 1;

/**
 * Rotate normalized-then-denormalized landmark points so the eye line is
 * horizontal, around the eye-line midpoint. Returns pixel-space points in
 * the SAME coordinate system the caller passed in (not re-normalized).
 *
 * @param {{x:number,y:number}[]} landmarksPx
 * @returns {{ landmarks: {x:number,y:number}[], rollDeg: number }}
 */
export function alignLandmarks(landmarksPx) {
  const l = landmarksPx[IDX.eyeOuterLeft];
  const r = landmarksPx[IDX.eyeOuterRight];
  const roll = Math.atan2(r.y - l.y, r.x - l.x); // 0 = eyes already level
  const cx = (l.x + r.x) / 2;
  const cy = (l.y + r.y) / 2;
  const cos = Math.cos(-roll);
  const sin = Math.sin(-roll);

  const landmarks = landmarksPx.map((p) => ({
    x: cx + (p.x - cx) * cos - (p.y - cy) * sin,
    y: cy + (p.x - cx) * sin + (p.y - cy) * cos,
  }));

  return { landmarks, rollDeg: (roll * 180) / Math.PI };
}

function dist(a, b) {
  return Math.hypot(a.x - b.x, a.y - b.y);
}

/**
 * Denormalize + roll-align landmarks, then compute the dimensionless ratios
 * `classifyFaceShape` decides on.
 *
 * @param {{x:number,y:number,z?:number}[]} landmarksNorm - normalized [0,1]
 *   landmarks from detectFaceLandmarksMP() (src/utils/faceLandmarkerMP.js).
 * @param {number} imgWidth
 * @param {number} imgHeight
 * @returns {{
 *   heightToWidth:number, jawToFace:number, jawToCheek:number,
 *   foreheadToJaw:number, rollDeg:number,
 *   raw:{faceHeight:number,faceWidth:number,jawWidth:number,foreheadWidth:number}
 * }}
 */
export function measureFaceGeometry(landmarksNorm, imgWidth, imgHeight) {
  if (!Array.isArray(landmarksNorm) || landmarksNorm.length < MIN_LANDMARKS) {
    throw new Error(
      `measureFaceGeometry: expected >= ${MIN_LANDMARKS} face landmarks, got ${landmarksNorm?.length ?? 0}`
    );
  }
  const px = landmarksNorm.map((p) => ({ x: p.x * imgWidth, y: p.y * imgHeight }));
  const { landmarks: aligned, rollDeg } = alignLandmarks(px);

  const faceHeight = dist(aligned[IDX.foreheadTop], aligned[IDX.chinBottom]);
  const faceWidth = dist(aligned[IDX.faceLeft], aligned[IDX.faceRight]);
  const jawWidth = dist(aligned[IDX.jawLeft], aligned[IDX.jawRight]);
  const foreheadWidth = dist(aligned[IDX.browLeft], aligned[IDX.browRight]);

  return {
    heightToWidth: faceHeight / faceWidth,
    jawToFace: jawWidth / faceWidth,
    // NOTE: the old face-api.js module measured "cheek width" (pts 1-15) as a
    // slightly different span than "face width" (pts 0-16) -- two nearly-
    // identical measurements standing in for one concept. Here `faceWidth`
    // (234<->454) already IS the cheekbone/temple width, so jawToCheek and
    // jawToFace are the same ratio; kept as two fields so
    // classifyFaceShape()'s decision tree (ported unchanged) still reads
    // naturally, but they will always be numerically equal.
    jawToCheek: jawWidth / faceWidth,
    foreheadToJaw: foreheadWidth / jawWidth,
    rollDeg,
    raw: { faceHeight, faceWidth, jawWidth, foreheadWidth },
  };
}

// Boundary values a ratio would need to cross to flip the decision, used
// only to build an honest confidence/margin number -- see classifyFaceShape.
const SCALE = { heightToWidth: 0.35, jawToFace: 0.15, jawToCheek: 0.15, foreheadToJaw: 0.35 };

function marginConfidence(value, threshold, scale) {
  return Math.max(0, Math.min(1, Math.abs(value - threshold) / scale));
}

/**
 * LEGACY threshold classifier -- not used by the app (see the module
 * header). Classify a face shape from the ratios `measureFaceGeometry` produces.
 *
 * Decision thresholds are carried over UNCHANGED from the retired
 * face-api.js-based classifier (still not calibrated against a labeled
 * dataset -- audit Phase 12). `confidence` is NOT a statistical probability;
 * it is the normalized distance from the ratio that decided the branch to
 * the threshold that would have flipped it, clipped to [0,1] -- a value
 * near 0 means the measurement is sitting right on a decision boundary
 * (report it as ambiguous), not "0% confident nothing was found."
 *
 * @returns {{ shape:string, confidence:number, measurements:object, quality:object }}
 */
// Decision boundaries for classifyFaceShape. Overridable so
// scripts/calibrate_face_shape.mjs can search alternatives against labeled
// photos without forking the decision tree.
export const DEFAULT_THRESHOLDS = {
  rectangleHW: 1.7,
  shortHW: 1.35,
  squareJaw: 0.75,
  heartFJ: 1.2,
  diamondFJ: 0.85,
  diamondJC: 0.8,
};

export function classifyFaceShape(measurements, thresholds = DEFAULT_THRESHOLDS) {
  const { heightToWidth, jawToFace, jawToCheek, foreheadToJaw } = measurements;
  const T = { ...DEFAULT_THRESHOLDS, ...thresholds };
  let shape;
  let confidence;

  if (heightToWidth > T.rectangleHW) {
    shape = "Rectangle";
    confidence = marginConfidence(heightToWidth, T.rectangleHW, SCALE.heightToWidth);
  } else if (heightToWidth < T.shortHW && jawToFace > T.squareJaw) {
    shape = "Square";
    confidence = Math.min(
      marginConfidence(heightToWidth, T.shortHW, SCALE.heightToWidth),
      marginConfidence(jawToFace, T.squareJaw, SCALE.jawToFace)
    );
  } else if (heightToWidth < T.shortHW && jawToFace <= T.squareJaw) {
    shape = "Round";
    confidence = Math.min(
      marginConfidence(heightToWidth, T.shortHW, SCALE.heightToWidth),
      marginConfidence(jawToFace, T.squareJaw, SCALE.jawToFace)
    );
  } else if (foreheadToJaw > T.heartFJ) {
    shape = "Heart";
    confidence = marginConfidence(foreheadToJaw, T.heartFJ, SCALE.foreheadToJaw);
  } else if (foreheadToJaw < T.diamondFJ && jawToCheek < T.diamondJC) {
    shape = "Diamond";
    confidence = Math.min(
      marginConfidence(foreheadToJaw, T.diamondFJ, SCALE.foreheadToJaw),
      marginConfidence(jawToCheek, T.diamondJC, SCALE.jawToCheek)
    );
  } else {
    shape = "Oval";
    // Oval is the "none of the above" default -- its confidence is how far
    // the ratios sit from every OTHER shape's nearest boundary.
    confidence = Math.min(
      marginConfidence(heightToWidth, T.shortHW, SCALE.heightToWidth),
      marginConfidence(heightToWidth, T.rectangleHW, SCALE.heightToWidth),
      marginConfidence(foreheadToJaw, T.heartFJ, SCALE.foreheadToJaw),
      marginConfidence(foreheadToJaw, T.diamondFJ, SCALE.foreheadToJaw)
    );
  }

  return {
    shape,
    confidence: Math.round(confidence * 1000) / 1000,
    measurements,
    quality: {
      rollDeg: measurements.rollDeg,
      // A large residual roll after alignment (e.g. extreme head tilt the
      // eye-line heuristic can't fully correct) is a real accuracy risk --
      // surfaced here rather than silently trusted.
      highRoll: Math.abs(measurements.rollDeg) > 15,
    },
  };
}

// The six shapes shown on the home page -- the only values
// detectFaceShapeFromLandmarks() returns.
export const FACE_SHAPES = faceShapeModel.classes;

/**
 * Feature vector the trained model expects: the FACE_OVAL ring, roll-aligned
 * on the eye corners, centered on the ring centroid and divided by
 * cheekbone width. Must stay identical to `features()` in
 * personal_color_ai/face_shape/train_landmark_model.py.
 */
export function faceOvalFeatures(landmarksNorm, imgWidth, imgHeight) {
  if (!Array.isArray(landmarksNorm) || landmarksNorm.length < MIN_LANDMARKS) {
    throw new Error(
      `faceOvalFeatures: expected >= ${MIN_LANDMARKS} face landmarks, got ${landmarksNorm?.length ?? 0}`
    );
  }
  const px = landmarksNorm.map((p) => ({ x: p.x * imgWidth, y: p.y * imgHeight }));
  const { landmarks: aligned } = alignLandmarks(px);
  const ring = faceShapeModel.landmarks.map((i) => aligned[i]);
  const cx = ring.reduce((s, p) => s + p.x, 0) / ring.length;
  const cy = ring.reduce((s, p) => s + p.y, 0) / ring.length;
  const width = dist(aligned[IDX.faceLeft], aligned[IDX.faceRight]);
  return ring.flatMap((p) => [(p.x - cx) / width, (p.y - cy) / width]);
}

/**
 * Multinomial logistic regression over faceOvalFeatures(). `confidence` is
 * the top class probability; `runnerUp` is the second most likely shape,
 * worth showing when the two are close (the model is ~25% accurate on a
 * 6-class problem -- see faceShapeModel.evaluation).
 */
export function predictFaceShape(features) {
  const { mean, scale, coef, intercept, classes } = faceShapeModel;
  const z = features.map((v, i) => (v - mean[i]) / scale[i]);
  const logits = coef.map((w, k) => w.reduce((s, wi, i) => s + wi * z[i], intercept[k]));
  const max = Math.max(...logits);
  const exps = logits.map((l) => Math.exp(l - max));
  const total = exps.reduce((s, e) => s + e, 0);
  const probabilities = Object.fromEntries(classes.map((c, k) => [c, exps[k] / total]));
  const ranked = [...classes].sort((a, b) => probabilities[b] - probabilities[a]);
  return {
    shape: ranked[0],
    confidence: Math.round(probabilities[ranked[0]] * 1000) / 1000,
    runnerUp: ranked[1],
    probabilities,
  };
}

/**
 * Convenience one-shot: landmarks -> trained-model classification, plus the
 * ratio measurements the image-quality gate and AI call log rely on.
 */
export function detectFaceShapeFromLandmarks(landmarksNorm, imgWidth, imgHeight) {
  const measurements = measureFaceGeometry(landmarksNorm, imgWidth, imgHeight);
  const prediction = predictFaceShape(faceOvalFeatures(landmarksNorm, imgWidth, imgHeight));
  return {
    ...prediction,
    measurements,
    quality: {
      rollDeg: measurements.rollDeg,
      highRoll: Math.abs(measurements.rollDeg) > 15,
    },
  };
}
